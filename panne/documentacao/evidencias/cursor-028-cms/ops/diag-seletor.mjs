import { chromium } from "playwright";
import { readFileSync } from "fs";
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const jwt = require("C:/Projetos/leaction-platform/services/gateway-api/node_modules/jsonwebtoken");
const env = readFileSync("C:/Projetos/leaction-platform/.env","utf8");
const secret = env.split(/\r?\n/).find(l=>l.startsWith("JWT_SECRET=")).slice(11).trim().replace(/^"|"$/g,"");
const token = jwt.sign({sub:"diag",email:"admin@actionhub.com.br"}, secret, {expiresIn:"20m"});
const session = { user:{id:"diag",email:"admin@actionhub.com.br",name:"Diag"}, token };
const browser = await chromium.launch({headless:true});
const page = await browser.newPage();
page.on("console", m => console.log("CONSOLE", m.type(), m.text()));
page.on("pageerror", e => console.log("PAGEERROR", e.message));
page.on("requestfailed", r => console.log("REQFAIL", r.url(), r.failure()?.errorText));
await page.addInitScript((s) => localStorage.setItem("actionhub_session", JSON.stringify(s)), session);
await page.goto("http://127.0.0.1:4000/dashboard/cms/site", {waitUntil:"domcontentloaded", timeout:30000});
await page.waitForTimeout(8000);
console.log("BODY", (await page.locator("body").innerText()).slice(0,500));
console.log("HAS_SELECT", await page.locator("select").count());
await browser.close();
